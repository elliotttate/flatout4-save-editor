# Regenerates Services/FlatOut4CareerTracks.cs from the game's career event definitions:
#   python scripts/gen_career_tracks.py <repo-root> Services/FlatOut4CareerTracks.cs
# Reads Flatout/Data/Common/Tuning/Factories/Events{Derby,Classic,AllStars}Level{0,1,2}.cfg and
# Flatout/Code/Sources/LOCALISATION.h. A track's save slot is its LocaId minus TRACK_ENV_DESERT_01,
# the same numbering FlatOut4GameData.TrackName uses. Reward blocks also name tracks (unlocks),
# so only each event's Tracks block is read.
import os
import re
import sys

repo, out = sys.argv[1], sys.argv[2]
factories = os.path.join(repo, 'Flatout', 'Data', 'Common', 'Tuning', 'Factories')
loca_path = os.path.join(repo, 'Flatout', 'Code', 'Sources', 'LOCALISATION.h')

loca_ids = {}
for line in open(loca_path, encoding='utf-8', errors='replace'):
    m = re.match(r'\s*static const LocaId (\w+) = (\d+);', line)
    if m:
        loca_ids[m.group(1)] = int(m.group(2))
first_track = loca_ids['TRACK_ENV_DESERT_01']


def block_after(text, start):
    # The body of the "{ ... }" that opens at or after start.
    open_at = text.index('{', start)
    depth, i = 1, open_at + 1
    while depth:
        depth += {'{': 1, '}': -1}.get(text[i], 0)
        i += 1
    return text[open_at + 1:i - 1]


def children(body):
    # Top-level "{ ... }" entries of a list body.
    result, depth, start = [], 0, None
    for i, c in enumerate(body):
        if c == '{':
            if depth == 0:
                start = i + 1
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                result.append(body[start:i])
    return result


events = []
for cls in ('Derby', 'Classic', 'AllStars'):
    for level in range(3):
        path = os.path.join(factories, 'Events%sLevel%d.cfg' % (cls, level))
        text = re.sub(r'--[^\n]*', '', open(path, encoding='utf-8', errors='replace').read())
        for m in re.finditer(r'\bEvent\d+\s*=\s*\{', text):
            body = block_after(text, m.start())
            index = re.search(r'\bIndex\s*=\s*"(\w+)"', body)
            tracks_at = re.search(r'\bTracks\s*=\s*\{', body)
            if not index or not tracks_at:
                continue
            rounds = []
            for entry in children(block_after(body, tracks_at.start())):
                track = re.search(r'\bTrackName\s*=\s*LocalesId\.(\w+)', entry)
                mode = re.search(r'\bType\s*=\s*"(\w+)"', entry)
                if track and mode and track.group(1) in loca_ids:
                    rounds.append((loca_ids[track.group(1)] - first_track, mode.group(1)))
            events.append((index.group(1), rounds))

lines = [
    '// <auto-generated>',
    '// Generated by scripts/gen_career_tracks.py from the game\'s Events*Level*.cfg factories.',
    '// </auto-generated>',
    'namespace FlatOut4SaveEditor.Services;',
    '',
    'public static class FlatOut4CareerTracks',
    '{',
    '    // Career event index -> the rounds it plays: track slot (see FlatOut4GameData.TrackName) and game mode.',
    '    public static readonly IReadOnlyDictionary<string, (int Track, string Mode)[]> Rounds = new Dictionary<string, (int Track, string Mode)[]>',
    '    {',
]
for index, rounds in events:
    items = ', '.join('(%d, "%s")' % r for r in rounds)
    lines.append('        ["%s"] = [%s],' % (index, items))
lines[-1] = lines[-1].rstrip(',')
lines += ['    };', '}', '']
open(out, 'w', encoding='utf-8', newline='\r\n').write('\n'.join(lines))
print('%d events, %d rounds' % (len(events), sum(len(r) for _, r in events)))
