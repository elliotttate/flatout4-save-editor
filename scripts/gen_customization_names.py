# Regenerates Services/FlatOut4CustomizationNames.cs from the game's data and localisation:
#   python scripts/gen_customization_names.py <repo-root> Services/FlatOut4CustomizationNames.cs
# Reads Flatout/Data/Common/Tuning/Factories/{CarsSkins,BoostFX,Horns,Drivers}.cfg and
# Flatout/Code/Sources/LOCALISATION.h (English text is the first column of each comment).
import os
import re
import sys

repo, out = sys.argv[1], sys.argv[2]
factories = os.path.join(repo, 'Flatout', 'Data', 'Common', 'Tuning', 'Factories')
loca_path = os.path.join(repo, 'Flatout', 'Code', 'Sources', 'LOCALISATION.h')

loca = {}
for line in open(loca_path, encoding='utf-8', errors='replace'):
    m = re.match(r'\s*static const LocaId (\w+) = (\d+); // (.*?) \| ', line)
    if m:
        loca[m.group(1)] = m.group(3).strip()


def fnv(text):
    value = 0
    for c in text.upper():
        value = (value * 16777619) & 0xFFFFFFFF
        value ^= ord(c)
    return value


def blocks(path, prefix):
    # Top-level "KEY = { ... }" entries; nested braces (offsets, vectors) are skipped over.
    text = open(path, encoding='utf-8', errors='replace').read()
    text = re.sub(r'--[^\n]*', '', text)
    result = []
    for m in re.finditer(r'\b(' + prefix + r'\w*)\s*=\s*\{', text):
        depth, i = 1, m.end()
        while depth and i < len(text):
            depth += {'{': 1, '}': -1}.get(text[i], 0)
            i += 1
        result.append((m.group(1), text[m.end():i - 1]))
    return result


def field(body, name):
    m = re.search(r'\b' + name + r'\s*=\s*("?)([^",\n]+)\1', body)
    return m.group(2).strip() if m else None


def loca_name(body, fallback):
    key = field(body, 'Name')
    key = key.split('.')[-1] if key else None
    text = loca.get(key) if key else None
    return text if text and not text.startswith('MENU_') else fallback


# Skins without English text (the FlatOut 2 ports) are named from their key's number, "Skin 3".
# The car is kept as its CarType key; FlatOut4CustomizationNames.CarSkins names it the way the
# garage does (FlatOut4GameData.CarTypeLabel).
skins = []
for key, body in blocks(os.path.join(factories, 'CarsSkins.cfg'), 'SKIN_'):
    number = re.search(r'_(\d+)$', key)
    name = loca_name(body, 'Skin %d' % int(number.group(1)) if number else key)
    skins.append((fnv(key), (name, field(body, 'CarType') or '')))

boosts = [(fnv(key), loca_name(body, key)) for key, body in blocks(os.path.join(factories, 'BoostFX.cfg'), 'BOOST_')]
horns = [(fnv(key), loca_name(body, key)) for key, body in blocks(os.path.join(factories, 'Horns.cfg'), 'HORN_')]

# Garage driver slots and loadouts store the FODriverName enum: DRIVER_01..12, DRIVER_DLC_0..17, then _None_.
driver_entries = dict(blocks(os.path.join(factories, 'Drivers.cfg'), 'DRIVER_'))
driver_order = ['DRIVER_%02d' % i for i in range(1, 13)] + ['DRIVER_DLC_%d' % i for i in range(18)]
drivers = []
for index, key in enumerate(driver_order):
    body = driver_entries.get(key)
    drivers.append((index, loca_name(body, key) if body else key))
drivers.append((len(driver_order), 'None'))


def cs_string(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def emit(name, pairs, comment, value_type='string', access='public'):
    seen = {}
    for key, label in pairs:
        seen.setdefault(key, label)
    if value_type == 'string':
        values = {key: cs_string(label) for key, label in seen.items()}
    else:
        values = {key: '(%s, %s)' % (cs_string(label[0]), cs_string(label[1])) for key, label in seen.items()}
    body = ',\n'.join('        [%d] = %s' % (key, value) for key, value in values.items())
    return '    // %s\n    %s static IReadOnlyDictionary<long, %s> %s { get; } = new Dictionary<long, %s>\n    {\n%s\n    };\n' % (
        comment, access, value_type, name, value_type, body)


text = ('namespace FlatOut4SaveEditor.Services;\n\n'
        '// Names for the garage ids, from the game\'s customization factories and LOCALISATION.h.\n'
        '// Generated by scripts/gen_customization_names.py; regenerate rather than hand-edit.\n'
        'public static partial class FlatOut4CustomizationNames\n{\n'
        + emit('CarSkinParts', skins, 'FNV hash of the CarsSkins.cfg key (CustomizationData::m_iId): skin name and CarType key.',
               value_type='(string Name, string CarType)', access='private') + '\n'
        + emit('BoostEffects', boosts, 'FNV hash of the BoostFX.cfg key.') + '\n'
        + emit('Horns', horns, 'FNV hash of the Horns.cfg key.') + '\n'
        + emit('Drivers', drivers, 'FODriverName enum value.') + '}\n')
open(out, 'w', encoding='utf-8', newline='\r\n').write(text)
print('skins', len(skins), 'boosts', len(boosts), 'horns', len(horns), 'drivers', len(drivers))
